"""공시 유형 분류. 분석 대상은 '거래소 수시공시 + 주요사항보고서' 뿐이다.

## 왜 블랙리스트인가

- 코드 필드(BIGCD·BONCD·SRCCD·IMPCD·SKCD·FUNCCD)는 **전부 단일값** → 구분력 0.
- MTVCD 는 공시 유형이 아니라 **시장 구분**(300 유가 · 320 코스닥 · 310 선옵 · 330 코넥스 · 360 시장경보).
- 제목에 **"주요사항보고서" 문자열은 존재하지 않는다.** 이 피드는 DART 원문이 아니라 거래소 스트림이라,
  주요사항보고서 항목들(회생절차개시신청·유상증자결정 등)이 **개별 제목**으로 온다.
- 수시공시 키워드를 열거하는 화이트리스트는 성립하지 않는다. 공시 종류가 너무 많아 반드시 샌다
  (전환가액조정·파생상품거래손실발생·채무보증결정·주식소각결정·횡령배임 …).

→ **거래소가 스스로 내는 것(시장조치·통계·상품·상장처리)을 빼고, 나머지를 기업 수시공시로 본다.**
   커버리지 100%.

## 버킷

| 버킷 | 내용 | 분석 대상 |
| --- | --- | --- |
| `수시공시` | 기업 제출 수시공시 + 주요사항보고서 항목 | **○ 유일한 비용 산정 기준** |
| `시장조치` | 투자주의/경고/위험·단기과열·공매도과열·소수계좌·불성실공시·관리종목·매매정지·상장폐지 **+ 기타시장안내·안내사항·매매방법(거래소 시장운영 공지)** | ✗ 거래소 발동 |
| `상장조치` | 신규/추가/변경상장·기준가격안내 | ✗ 제외 확정 (거래소 상장 처리) |
| `통계안내` | 회전율/변동성/거래량 상위·대량매매내역 | ✗ |
| `상품공시` | ETF/ETN/ELW·유동성공급자(LP)·지수산출 | ✗ |

코스닥 7일 표본 실측: 수시공시 888(68.3%) · 시장조치 259(19.9%) · 상장조치 110(8.5%) · 통계안내 43(3.3%).
→ **공시부 심사 물량 = 수시공시뿐.** 나머지 31.7%는 비용 산정에서 뺀다.

## 판정 알고리즘

1. 제목의 **공백을 전부 제거**한다(유일한 regex 용도). "공매도 과열" / "공매도과열" 표기 흔들림 흡수.
2. **배제 목록을 순서대로** 부분문자열 검사 → 걸리면 그 버킷.
3. 아무것도 안 걸리면 **`수시공시`**.

**`수시공시`에는 키워드 목록이 없다. 잔여물로 정의된다.** 순서가 의미를 만든다:
"불성실공시법인 지정"은 '공시'를 포함하지만 시장조치에 먼저 걸리고, "추가상장(국내사모 CB전환)"은
'전환'을 포함하지만 상장조치에 먼저 걸린다.

**약점**: 블랙리스트에 없는 표현의 거래소 발신 공시는 수시공시로 **오분류**된다.
→ **키워드를 손대면 `audit_gongsi.py`를 반드시 다시 돌린다.** 표본으로 짠 블랙리스트는 샌다.
"""

from __future__ import annotations

import re

# ── 거래소가 스스로 발동하는 시장조치·경보·시장운영 안내 (공시부 수시공시 심사 물량 아님) ──
# '기타시장안내'·'안내사항'·'매매방법'은 거래소 시장운영 공지이므로 통계가 아니라 시장조치로 분류한다.
MARKET_ACTION = [
    "투자주의", "투자경고", "투자위험", "시장경보", "투자환기",
    "단기과열", "공매도과열", "소수계좌", "불성실공시법인",
    "관리종목", "매매거래정지", "매매거래재개", "상장폐지", "정리매매", "상장적격성",
    "기타시장안내", "안내사항", "시장조치", "매매방법",
    "일시효력정지", "Sidecar", "사이드카",       # ⚠ '효력정지'로 줄이면 기업공시 '주주총회결의효력정지가처분'이 빨려든다
    "매매거래일시중단",                          # 1단계 CB 발동
    "휴장안내",
    "배당락",                                   # 거래소 배당락 안내 (기업의 '배당기준일 안내'와는 다르다)
    "상호변경안내", "결산기변경안내",             # ⚠ '변경안내'로 줄이면 기업공시 '배당기준일 변경 안내'가 빨려든다
]
# ── 거래소 통계 공시 (순위·집계) ──
NOTICE_STAT = [
    "회전율상위", "변동성상위", "거래량증가율상위", "상승(하락)율상위", "종목(코스닥시장)",
    "대량매매내역",
    "자기주식매매신청내역", "자기주식매매체결내역",   # 거래소가 매일 1건씩 내는 시장 집계 (606일에 607건)
]
# ── ETF/ETN/ELW 등 상품·발행사 공시 ──
PRODUCT = [
    "ELW", "ETN", "ETF", "상장지수", "유동성공급", "지수산출", "괴리율",
    "주식선물", "주식옵션", "가격제한폭확대",
]
# ── 거래소 상장 처리 (제외 확정) ──
LISTING = [
    "신규상장", "추가상장", "변경상장", "재상장", "기준가격안내", "기준가격", "상장폐지신청",
    "기준가산정",   # 606일 감사 추가. 실제 표현은 '기준가격안내'가 아니라 '기준가산정 등에 관한 안내'
]

_SP = re.compile(r"\s+")


def _norm(title: str) -> str:
    return _SP.sub("", title or "")


def bucket(title: str) -> str:
    t = _norm(title)
    if any(k in t for k in MARKET_ACTION):
        return "시장조치"
    if any(k in t for k in NOTICE_STAT):
        return "통계안내"
    if any(k in t for k in PRODUCT):
        return "상품공시"
    if any(k in t for k in LISTING):
        return "상장조치"
    return "수시공시"


# ⚠ 여기에 `SUBTYPE`(부실신호·자본조달·지배구조… 키워드 사전)이 있었으나 **삭제했다.**
#
# 그것으로 "부실신호 공시 2,493건 중 77.2%가 애프터"라는 수치를 냈었는데, 두 가지가 문제였다.
#   1. **재현이 안 됐다.** 그 수치를 만든 스크립트가 리포에 없었다(임시 코드였다).
#   2. **키워드 선택이 곧 공격 지점이었다.** "왜 그 키워드냐"에 답할 근거가 없다.
#
# → **`halt_triggers.py`가 이를 대체한다.** 거래소가 **실제로 거래를 멈춘 사건**만 세므로
#   내가 고를 여지가 없다. 정지 공시 제목에 사유가 붙어 있다(910건 100%).
#   결과: REPORT §3-2 · 부록 D · `output/halt_events.csv`.
#
# **부실 공시를 키워드로 다시 고르려 하지 말 것.** 그 길은 이미 한 번 막혔다.


def is_correction(title: str) -> bool:
    """(정정) 공시. 정정 자체가 공시 품질 신호이므로 별도 카운트.

    제목은 **회사명으로 시작**한다("하나머티리얼즈(주) (정정)최대주주 변경…") → startswith 로는 못 잡는다.
    """
    return "(정정)" in _norm(title)


AFTER_START, AFTER_END = 154000, 200000


def is_after_hours(time_str: str) -> bool:
    """TIME = HHMMSS. 애프터 세션(15:40~20:00) 발표 공시."""
    try:
        t = int((time_str or "0")[:6])
    except ValueError:
        return False
    return AFTER_START <= t <= AFTER_END
